const ENDING_MODEL = "gemini-3.1-flash-lite";

export async function onRequestPost(context: any) {
  const { request, env } = context;

  if (!env.GEMINI_API_KEY) {
    return Response.json(
      { error: "GEMINI_API_KEY is missing" },
      { status: 500 }
    );
  }

  let body;

  try {
    body = await request.json();
  } catch {
    return Response.json(
      { error: "Request body must be valid JSON" },
      { status: 400 }
    );
  }

  const {
    scenario,
    currentStatus,
    progress,
    maxProgress,
    currentSituation,
    history = [],
    endingType,
    failedStatusKey,
    failedStatusLabel
  } = body;

  const clearInstruction = endingType === "clear" ? `今回は clear エンドです。必ず成功エンドにしてください。失敗・破滅・社会的死亡・死亡・帰還不能は禁止です。` : "";

  const prompt = `
    あなたはノベルゲーム風サバイバルゲームのエンディング作家です。
    以下のプレイ内容をもとに、ゲームの結末文を日本語で作ってください。

    シナリオ:
    ${JSON.stringify(scenario)}

    最終ステータス:
    ${JSON.stringify(currentStatus)}

    最後の状況:
    ${currentSituation}

    プレイヤーの行動履歴:
    ${JSON.stringify(history)}

    目的達成進行度:
    ${JSON.stringify(progress)} / ${JSON.stringify(maxProgress)}

    endingType:
    ${JSON.stringify(endingType)}

    ${clearInstruction}

    エンディングの文体ルール:
    - endingTextは、単なる結果報告ではなく、短編小説のラストシーンとして書いてください
    - ただし、視点はこれまでの行動履歴と同じにしてください
    - 主人公の呼称は必ず行動履歴の文と同じにしてください
    - 今までの履歴で、主人公が「あなた」と呼ばれている場合は、必ずエンディングでも「あなた」としてください
    - 無難な説明文で終わらせず、印象に残る結末にしてください
    - これまでの行動履歴から、特に変だった行動・印象的だった行動・繰り返された行動を1〜3個拾い、結末に必ず反映してください
    - プレイヤーの選択が「だからこの結末になった」と感じられるようにしてください
    - ただ状況を説明するだけでなく、最後に象徴的な物・言葉・痕跡・風景を残してください
    - ジャンルに合っていれば、皮肉、奇妙な美しさ、後味の悪さ、救い、笑える因果応報を入れて構いません
    - ただし、ギャグに寄せすぎず、物語として締まる文章にしてください
    - 最後の一文は、読後に余韻が残る強い一文にしてください

    エンディングの構成:
    - 1段落目: 最後の行動によって何が起きたかを書く
    - 2段落目: 最終的に成功・失敗・生還・変質など、どう決着したかを確定させる
    - 3段落目: その後の人生・残った傷跡・象徴的な持ち物や言葉を書く
    - 「数日後」「その後」などの時間経過は使ってよいが、プレイ中に起きていない出来事を大きく作りすぎない
    - 最後の一文では、履歴に出てきた持ち物・変な行動・印象的な場所のどれかを使って締める

    避ける表現:
    - 「平穏を取り戻せなかった」だけの抽象的な締め
    - 「恐怖に塗り潰された」など、どのホラーにも使える汎用表現
    - 具体的にどう助かった/どう失敗したのかが分からない文章

    避けるべきエンディング:
    - 「あなたは生き延びた」「あなたは失敗した」だけの結果報告
    - 「その後どうなったかは分からない」という未確定の締め
    - 行動履歴と関係ない汎用的な結末
    - どのジャンルでも使えるような無難な文章
    - 目的達成進行度やendingTypeと矛盾する結末

    行動履歴の使い方:
    - historyから、結末に使うべき「印象的な行動」を必ず選んでください
    - 特に、ふざけた行動、無謀な行動、繰り返された行動、持ち物を使った行動、誰かと関わった行動を優先してください
    - その行動が、成功・失敗・変質・救助・代償のどれにつながったのかを描いてください
    - もしプレイヤーが奇妙な行動をしていた場合、その奇妙さを無視せず、世界側がそれに反応した結果として結末を書いてください

    履歴の整合性ルール:
    - historyに出てきた重要な事実を無視しないでください
    - 「可能性が濃厚」「発見した」「判明した」と書かれている情報は、結末で必ず扱ってください
    - 既に強く示された事実を、理由なく「真相は分からない」に戻さないでください
    - ただし、証拠が失われた、証明できなかった、周囲に信じてもらえなかった、という形で失敗させるのは許可します
    - エンディングを書く前に、履歴から重要な事実を3つ選び、それらを必ず本文に反映してください

    社会的・仕事・炎上系ジャンルのルール:
    - 物理的な死や怪物ではなく、信用、立場、証拠、人間関係、評価、記録、誤解、謝罪、処分を中心に結末を作ってください
    - 不自然な陰謀や超常現象に寄せすぎないでください
    - 「誰が悪かったのか」「何を証明できた/できなかったのか」「主人公の立場がどうなったのか」を明確にしてください

    結末の味付け:
    - シナリオ、endingType、progress、履歴に合うものを1つだけ選び、endingTextに自然に反映してください。
    - endingTypeと矛盾する味付けは選ばないでください。

    成功・完全勝利寄り:
    - 完全生還し、元の日常へ戻る結末
    - 目的を達成し、救助される結末
    - 危機を乗り越え、仲間や救助者に迎えられる結末
    - 最後の選択が見事に成功し、状況を逆転する結末
    - 失われかけた希望を取り戻す結末
    - 敵や脅威を退け、堂々と帰還する結末
    - 出口・脱出手段・解決策に辿り着き、明確に助かる結末
    - これまでの行動がすべて繋がり、納得感のある勝利になる結末
    - 誰かを助けたことで、自分も救われる結末
    - 持ち物や手がかりが最後に役立ち、綺麗に目的を達成する結末
    - ふざけた行動が奇跡的に噛み合い、なぜか大成功する結末
    - 小さな機転が最後に大きな勝利へ繋がる結末

    成功だが余韻あり:
    - 皮肉な成功
    - 代償つきの生還
    - 誰かに語り継がれる結末
    - 本人だけが真実を知る結末
    - 最後の持ち物が意味を持つ結末
    - 敵や味方との関係が反転する結末
    - 目的は達成したが、元の自分には戻れない結末

    バッドエンド寄り:
    - 逃げ場を失い、世界や場所に取り込まれる結末
    - 助かったと思った瞬間に、より悪い運命が確定する結末
    - 肉体や精神が変質し、別の存在として残される結末
    - 救助は来たが、主人公だけは戻れなかった結末
    - 目的地に辿り着いたが、そこ自体が罠だった結末
    - 味方だと思った存在に引き渡される結末
    - 自分の行動が原因で、危機をさらに広げてしまう結末
    - 最後の持ち物だけが発見され、本人は消える結末
    - 主人公の声・影・記録だけが残り続ける結末
    - 敵や怪異の一部として役割を与えられる結末
    - 社会的に完全敗北し、名前だけが悪い意味で残る結末
    - 目的は達成できず、別のルールの中で生き続ける結末
    - 死は免れたが、元の日常には二度と戻れない結末
    - ふざけた行動が最悪の形で世界に受理される結末
    - 小さな判断ミスが、取り返しのつかない結末へつながる結末

    clearの場合:
    - 基本的には成功・完全勝利寄りの味付けを優先してください
    - 必ずしも代償や皮肉を入れる必要はありません
    - プレイヤーの行動が十分に良かった場合は、素直に気持ちよく成功させてください
    - ただし、履歴にふざけた行動や危険な行動が多い場合は、少し変な成功や皮肉な成功にしても構いません

    badの場合:
    - 成功・救済・完全生還に見える味付けを選ばないでください。
    - ただし、単に「死んだ」で終わらせず、変質・消失・捕獲・社会的破滅・帰還不能・世界への取り込みなど、物語として印象に残る結末にしてください。

    ambiguousの場合:
    - 結末自体は確定させてください。
    - 「生死不明」だけで終わらせず、救助待ちで発見される、別の場所へ流れ着く、元の世界には戻れないが新しい役割を得る、など一区切りのある結果にしてください。

    最後の一文のルール:
    - 最後の一文は短く、印象的にしてください
    - 最後の一文には、今回のプレイを象徴する物・場所・言葉のどれかを入れてください
    - 最後の一文を疑問形で終わらせないでください

    最重要ルール:
    - endingType は絶対に守ってください
    - endingType が clear の場合、必ず目的達成・生還・脱出・勝利・名誉回復・炎上鎮火など、明確な成功結果にしてください
    - endingType が clear の場合、失敗・破滅・キャリア喪失・死亡・捕獲・帰還不能・炎上継続を結末にしてはいけません
    - endingType が clear の場合でも小さな代償や苦い後味は入れてよいですが、最終結果は必ず成功です
    - endingType が clear の最後の段落では「何を達成したのか」「その後どうなったのか」を成功として確定させてください
    - HTMLタグは禁止です。
    - <br>、<p>、<div> などのHTMLタグを絶対に使わないでください。
    - 段落の区切りは、必ずJSON文字列内の改行文字 \n\n で表現してください。

    エンディング種別(endingType)ごとの必須結果:
    - clear: 目的を達成し、生還・脱出・帰還・勝利・名誉回復・炎上鎮火・危機脱出のいずれかを明確に描く。最終結果は必ず成功。
    - costly_survival: 生き残る/危機を脱するが、怪我・喪失・呪い・記憶の欠落・評判低下・関係悪化など、明確な代償を残す。
    - ambiguous: 完全成功ではないが、一区切りついた確定結果にする。生死や状態を未確定にしない。
    - bad: 失敗、死亡、捕獲、変質、帰還不能、社会的破滅、世界に取り込まれるなど、明確なバッドエンドにする。

    社会的・仕事・炎上系ジャンルのclear:
    - clearの場合、問題は完全または実質的に解決します
    - 炎上系なら、謝罪・説明・証拠提示・新作発表・第三者の証言などにより、炎上は鎮火または沈静化します
    - 仕事系なら、重大な損失を回避し、信頼を一部または大きく回復します
    - 創作系なら、作品・説明・行動によって、クリエイターとしての道が残ります
    - clearで「信頼を決定的に失った」「筆を折った」「炎上はさらに燃えた」のような破滅エンドは禁止です

    尽きたステータス:
    ${failedStatusLabel || failedStatusKey || "なし"}

    条件:
    - 必ずJSONだけで返す
    - endingTitleは短いタイトルにする
    - endingTextは600文字以上、1000文字以下
    - endingTextは3段落に分けてください
    - JSONとして壊れないよう、段落の区切りは必ずエスケープされた改行記号 \\n\\n として出力してください
    - endingTextの文字列の中に、生の改行を直接入れないでください
    - <br> や <p> などのHTMLタグは禁止です
    - ただ「死んだ」で終わらせない
    - これまでの行動を少し振り返る
    - なぜその結末に至ったかを描写する
    - その後どうなったかを入れる
    - ジャンルに合った結末にする
    - バッドエンドでも、結末を確定させた上で物語として余韻を残す
    - 余韻とは、結末をぼかすことではありません。確定した結末のあとに残る感情・傷跡・記憶・世界の変化を書くことです。
    - 過度に残酷な描写は避ける
    - 実在の事件・災害を連想させる描写は避ける
    - 自傷や犯罪の具体的手順は書かない
    - endingTextの最後の一文は、必ず確定文にしてください
    - 最後の一文を疑問形や「〜かもしれない」で終わらせないでください

    尽きたステータスごとの方向性:
    - hp: 身体的な限界、負傷、行動不能、救助失敗、代償つき生存など
    - resource: 物資不足、選択肢の喪失、環境への屈服、取引や代償など
    - safety: 危険に捕まる、閉じ込められる、追跡される、支配されるなど
    - mental: 心の限界、認識の変化、記憶の混濁、別の役割を受け入れるなど
    - survive: 生存、脱出、救助、帰還、ただし小さな代償や後日談を含めてもよい

    結末の種類は固定しないでください。
    変質、孤立、捕獲、救助失敗、帰還不能、代償つき生存、記憶喪失、別存在化、閉じ込め、取り込まれる、役割の変化など、シナリオに合う形を自由に選んでください。
    上記の方向性は発想の軸であり、定型文や固定パターンではありません。シナリオ内容と行動履歴を優先して、毎回異なる結末を作ってください。

    結末確定のルール:
    - endingTextでは、主人公が最終的にどうなったのかを必ず確定させてください
    - 「まだ誰にも分からない」「この先どうなるのか」「〜かもしれない」「それとも…」のような未確定の締め方は禁止です
    - エンディングは次回予告ではなく、今回のプレイの最終結果です
    - 生還、脱出、死亡、救助、捕獲、変質、帰還不能、別存在化、代償つき生存など、最終状態を明確にしてください
    - 余韻は、結末を曖昧にするためではなく、確定した結末の後日談として入れてください
    - 最後の段落では「その後どうなったか」を具体的に書いてください

    返すJSON形式:
    {
      "endingTitle": "string",
      "endingText": "string"
    }
  `;

  const res = await fetch(
    `https://generativelanguage.googleapis.com/v1beta/models/${ENDING_MODEL}:generateContent?key=${env.GEMINI_API_KEY}`,
    {
      method: "POST",
      headers: {
        "Content-Type": "application/json"
      },
      body: JSON.stringify({
        contents: [
          {
            parts: [{ text: prompt }]
          }
        ],
        generationConfig: {
          responseMimeType: "application/json"
        }
      })
    }
  );

  const json = await res.json();
  const text = json?.candidates?.[0]?.content?.parts?.[0]?.text ?? "";
  const result = extractJson(text);

  return Response.json({
    ok: res.ok,
    status: res.status,
    result,
    usage: json.usageMetadata
  });
}

function extractJson(text: string) {
  const start = text.indexOf("{");
  const end = text.lastIndexOf("}");

  if (start === -1 || end === -1) {
    throw new Error("JSON not found");
  }

  return JSON.parse(text.slice(start, end + 1));
}
